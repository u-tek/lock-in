// The Live Activity wire format (SPEC.md §4.3), mirrored from the Swift `LockinAttributes` type in
// Packages/LKKit/Sources/Model.
//
// ActivityKit decodes content-state with the default JSONDecoder, so the key names, the JSON types
// and the absence of optional keys must match the Swift side exactly: a mismatch doesn't fail
// loudly, the update is silently dropped on the phone. Both sides test against the same files in
// fixtures/live-activity/. Change a key there, in Model, and here in the same commit.

import { APNS_BODY_LIMIT_BYTES } from "./apns.ts";

/** Member states, as the Int the Swift side decodes. Each has its own creature pose. */
export const MemberState = {
  focusing: 0,
  break: 1,
  paused: 2,
  done: 3,
  left: 4,
  slipped: 5,
} as const;
export type MemberState = (typeof MemberState)[keyof typeof MemberState];

/** Static attributes, set when the device starts the activity. */
export interface Attributes {
  /** Session (room) id. */
  sid: string;
  /** The device owner's member id, so one content-state serves every member of the room. */
  me: string;
  /** Squad name; absent when solo. */
  sq?: string;
}

export interface Member {
  /** Member id. */
  i: string;
  /** Display name. */
  n: string;
  /** Avatar code, `b<body>.c<colour>.e<eyes>.h<hat>`. */
  a: string;
  s: MemberState;
  /** Started at, Unix seconds. */
  b: number;
  /** Ends at, Unix seconds. While paused the time left is `e - q`. */
  e: number;
  /** Paused at, Unix seconds; present exactly when `s` is paused. */
  q?: number;
}

export interface Pet {
  /** Species and stage, e.g. `sprout.2`. */
  k: string;
  /** Mood, 0–3. */
  md: number;
  /** Progress to the next stage, 0–1. */
  x: number;
}

export interface Cheer {
  /** From member id. */
  f: string;
  /** To member id. */
  t: string;
  /** Cheer kind: an index into the app's emoji set. */
  k: number;
  /** Unix seconds. */
  at: number;
}

export interface ContentState {
  /** State version; only ever goes up. */
  v: number;
  /** Members in server order (host first). The views put `me` first themselves. */
  m: Member[];
  /** Squad pet; absent when solo. */
  p?: Pet;
  /** The most recent cheer, shown briefly. */
  c?: Cheer;
}

/** The Swift type name, which push-to-start payloads must name in `attributes-type`. */
export const ATTRIBUTES_TYPE = "LockinAttributes";

export const MAX_MEMBERS = 6;
export const MAX_NAME_LENGTH = 12;
export const MAX_SQUAD_NAME_LENGTH = 20;

/**
 * Our ceiling for attributes + content-state, as compact UTF-8 JSON. ActivityKit's hard limit is
 * 4096 bytes; the margin leaves room for fields we add later without a surprise on someone's phone.
 */
export const PAYLOAD_BUDGET_BYTES = 3584;

/** `stale-date` is the latest member's end plus this (SPEC.md §4.4). */
export const STALE_AFTER_END_SECONDS = 300;

/** An `end` push leaves the final state up for this long unless told otherwise (SPEC.md §4.4). */
export const END_DISMISSAL_SECONDS = 1800;

// Times must be Unix seconds. The range catches the two classic mistakes: milliseconds (1000x too
// big) and durations passed where a date belongs.
const EARLIEST_TIME = 946_684_800; // 2000-01-01T00:00:00Z
const LATEST_TIME = 4_102_444_800; // 2100-01-01T00:00:00Z

// These patterns and the length limits put a ceiling on every string, so the validators can't let
// through anything over budget: test/liveActivity.test.ts builds the worst case they allow and
// checks it fits. Widen one and that test says whether it still does.
const SHORT_ID = /^[0-9A-Za-z]{10}$/;
const AVATAR_CODE = /^[a-z][0-9]{1,2}(?:\.[a-z][0-9]{1,2}){0,3}$/;
// M7: a boosted squad's pet may wear an accessory after its stage, "sprout.2.a3" (`pet.3` in the
// shop's catalogue). Model's PetCode reads the species and stage and ignores the rest.
const PET_CODE = /^[a-z]{1,10}\.[0-9]{1,2}(?:\.a[0-9]{1,2})?$/;
const MAX_CHEER_KIND = 99;

// Control characters and lone surrogates turn into 6-byte `\uXXXX` escapes in JSON, which would
// break the 4-bytes-per-character worst case, and nobody needs them in a name.
const UNPRINTABLE = /[\p{Cc}\p{Cs}]/u;

export class LiveActivityError extends Error {
  override name = "LiveActivityError";
}

/** A pet code the parser accepts: `<species>.<stage>`, e.g. `sprout.2`, optionally with an accessory, `sprout.2.a3` (M7). */
export function isPetCode(value: unknown): value is string {
  return typeof value === "string" && PET_CODE.test(value);
}

/** Ids are 10 base62 characters, generated by the server (and by Core's ShortID for local ones). */
export function isShortID(value: unknown): value is string {
  return typeof value === "string" && SHORT_ID.test(value);
}

/**
 * Length as the server counts it: Unicode code points.
 *
 * Swift's `String.count` counts Characters (grapheme clusters), and a Character is one or more code
 * points, so anything within the limit here is within it on the phone too. Counting code points is
 * the stricter choice on purpose: a single grapheme can carry any number of combining marks, so
 * only code points put a ceiling on bytes (4 per code point in UTF-8). The app must validate names
 * the same way (`unicodeScalars.count`) or the server will refuse some names the app allowed.
 */
export function textLength(value: string): number {
  return [...value].length;
}

// Strict parsing. Messages name the exact path (`contentState.m[2].n`) because they go straight
// back to whoever sent the JSON.

type JSONObject = Record<string, unknown>;

function fail(path: string, message: string): never {
  throw new LiveActivityError(`${path} ${message}`);
}

/** An object with exactly these keys. `undefined` counts as absent, `null` never does. */
function object(value: unknown, path: string, required: readonly string[], optional: readonly string[] = []): JSONObject {
  if (typeof value !== "object" || value === null || Array.isArray(value)) fail(path, "must be an object");
  const record = value as JSONObject;
  for (const key of Object.keys(record)) {
    const keyPath = `${path}.${key}`;
    if (!required.includes(key) && !optional.includes(key)) {
      fail(keyPath, `isn't part of the wire format (expected ${[...required, ...optional].join(", ")})`);
    }
    if (record[key] === null) {
      fail(keyPath, optional.includes(key) ? "is null: leave optional keys out instead" : "is null");
    }
  }
  for (const key of required) {
    if (!Object.hasOwn(record, key) || record[key] === undefined) fail(`${path}.${key}`, "is missing");
  }
  return record;
}

function shortID(value: unknown, path: string): string {
  if (!isShortID(value)) fail(path, "must be a 10-character base62 id");
  return value;
}

function text(value: unknown, path: string, maxLength: number): string {
  if (typeof value !== "string") fail(path, "must be a string");
  const length = textLength(value);
  if (length === 0 || length > maxLength) fail(path, `must be 1–${maxLength} characters (code points), got ${length}`);
  if (UNPRINTABLE.test(value)) fail(path, "has control characters or broken surrogate pairs");
  return value;
}

function matching(value: unknown, path: string, pattern: RegExp, example: string): string {
  if (typeof value !== "string" || !pattern.test(value)) fail(path, `must look like "${example}"`);
  return value;
}

function integer(value: unknown, path: string, min: number, max: number): number {
  if (typeof value !== "number" || !Number.isInteger(value) || value < min || value > max) {
    fail(path, `must be a whole number from ${min} to ${max}`);
  }
  return value;
}

function fraction(value: unknown, path: string): number {
  if (typeof value !== "number" || !Number.isFinite(value) || value < 0 || value > 1) {
    fail(path, "must be a number from 0 to 1");
  }
  return value;
}

function time(value: unknown, path: string): number {
  if (typeof value !== "number" || !Number.isFinite(value)) fail(path, "must be a finite number of Unix seconds");
  if (value < EARLIEST_TIME || value > LATEST_TIME) {
    fail(path, `must be Unix seconds between 2000 and 2100, got ${value} (milliseconds are 1000x too big)`);
  }
  return value;
}

/** Validates attributes from untrusted JSON. Returns a fresh copy in canonical key order. */
export function parseAttributes(value: unknown, path = "attributes"): Attributes {
  const record = object(value, path, ["sid", "me"], ["sq"]);
  const attributes: Attributes = { sid: shortID(record.sid, `${path}.sid`), me: shortID(record.me, `${path}.me`) };
  if (record.sq !== undefined) attributes.sq = text(record.sq, `${path}.sq`, MAX_SQUAD_NAME_LENGTH);
  return attributes;
}

function parseMember(value: unknown, path: string): Member {
  const record = object(value, path, ["i", "n", "a", "s", "b", "e"], ["q"]);
  const member: Member = {
    i: shortID(record.i, `${path}.i`),
    n: text(record.n, `${path}.n`, MAX_NAME_LENGTH),
    a: matching(record.a, `${path}.a`, AVATAR_CODE, "b3.c7.e2.h4"),
    s: integer(record.s, `${path}.s`, MemberState.focusing, MemberState.slipped) as MemberState,
    b: time(record.b, `${path}.b`),
    e: time(record.e, `${path}.e`),
  };
  if (member.e < member.b) fail(`${path}.e`, "is before b");
  if (member.s === MemberState.paused) {
    if (record.q === undefined) fail(`${path}.q`, "is missing: a paused member needs its paused-at time");
    member.q = time(record.q, `${path}.q`);
    if (member.q < member.b || member.q > member.e) fail(`${path}.q`, "must be between b and e");
  } else if (record.q !== undefined) {
    fail(`${path}.q`, "is only for paused members (s = 2)");
  }
  return member;
}

function parsePet(value: unknown, path: string): Pet {
  const record = object(value, path, ["k", "md", "x"]);
  return {
    k: matching(record.k, `${path}.k`, PET_CODE, "sprout.2"),
    md: integer(record.md, `${path}.md`, 0, 3),
    x: fraction(record.x, `${path}.x`),
  };
}

function parseCheer(value: unknown, path: string): Cheer {
  const record = object(value, path, ["f", "t", "k", "at"]);
  return {
    f: shortID(record.f, `${path}.f`),
    t: shortID(record.t, `${path}.t`),
    k: integer(record.k, `${path}.k`, 0, MAX_CHEER_KIND),
    at: time(record.at, `${path}.at`),
  };
}

/** Validates a content-state from untrusted JSON. Returns a fresh copy in canonical key order. */
export function parseContentState(value: unknown, path = "contentState"): ContentState {
  const record = object(value, path, ["v", "m"], ["p", "c"]);
  const v = integer(record.v, `${path}.v`, 0, Number.MAX_SAFE_INTEGER);
  if (!Array.isArray(record.m)) fail(`${path}.m`, "must be an array");
  if (record.m.length === 0 || record.m.length > MAX_MEMBERS) {
    fail(`${path}.m`, `must have 1–${MAX_MEMBERS} members, got ${record.m.length}`);
  }
  const members = record.m.map((member, index) => parseMember(member, `${path}.m[${index}]`));
  const seen = new Set<string>();
  members.forEach((member, index) => {
    if (seen.has(member.i)) fail(`${path}.m[${index}].i`, `repeats member id ${member.i}`);
    seen.add(member.i);
  });

  const state: ContentState = { v, m: members };
  if (record.p !== undefined) state.p = parsePet(record.p, `${path}.p`);
  if (record.c !== undefined) state.c = parseCheer(record.c, `${path}.c`);
  return state;
}

/** A copy in the canonical key order, with absent optional keys left out (never `null`). */
export function canonicalAttributes(attributes: Attributes): Attributes {
  const canonical: Attributes = { sid: attributes.sid, me: attributes.me };
  if (attributes.sq !== undefined) canonical.sq = attributes.sq;
  return canonical;
}

function canonicalMember(member: Member): Member {
  const canonical: Member = { i: member.i, n: member.n, a: member.a, s: member.s, b: member.b, e: member.e };
  if (member.q !== undefined) canonical.q = member.q;
  return canonical;
}

/** A copy in the canonical key order (`v, m, p, c`; `i, n, a, s, b, e, q`), optional keys left out. */
export function canonicalContentState(state: ContentState): ContentState {
  const canonical: ContentState = { v: state.v, m: state.m.map(canonicalMember) };
  if (state.p !== undefined) canonical.p = { k: state.p.k, md: state.p.md, x: state.p.x };
  if (state.c !== undefined) canonical.c = { f: state.c.f, t: state.c.t, k: state.c.k, at: state.c.at };
  return canonical;
}

/** Compact JSON, exactly as it travels (and as the fixtures are written, minus whitespace). */
export function encodeAttributes(attributes: Attributes): string {
  return JSON.stringify(canonicalAttributes(attributes));
}

/** Compact JSON, exactly as it travels inside `aps.content-state`. */
export function encodeContentState(state: ContentState): string {
  return JSON.stringify(canonicalContentState(state));
}

const utf8 = new TextEncoder();

/** What counts against ActivityKit's 4 KB: attributes plus content-state, compact UTF-8 JSON. */
export function payloadByteCount(attributes: Attributes, state: ContentState): number {
  return utf8.encode(encodeAttributes(attributes)).length + utf8.encode(encodeContentState(state)).length;
}

/** Throws above `PAYLOAD_BUDGET_BYTES`; returns the byte count otherwise. */
export function assertPayloadBudget(attributes: Attributes, state: ContentState): number {
  const bytes = payloadByteCount(attributes, state);
  if (bytes > PAYLOAD_BUDGET_BYTES) {
    throw new LiveActivityError(
      `Live Activity data is ${bytes} bytes (attributes + content-state); the budget is ${PAYLOAD_BUDGET_BYTES}`,
    );
  }
  return bytes;
}

/**
 * When the activity should look stale if no update has arrived: five minutes after the last running
 * timer should end. Same rule as Swift's `ContentState.staleDate(now:)` (Model), so the app and the
 * server never disagree:
 * - only running members count (focusing, on a break, paused, slipped: a slip shows while the timer
 *   keeps running, decision 0009); done and left members don't hold the activity open, unless
 *   nobody is running, when everyone's end counts;
 * - a paused member's end keeps moving, so it counts as `now` plus the time they have left.
 * Whole seconds, rounded up, because APNs dates are integers.
 */
export function staleDateFor(state: ContentState, now: number): number {
  const running = state.m.filter(
    (member) =>
      member.s === MemberState.focusing || member.s === MemberState.break || member.s === MemberState.paused || member.s === MemberState.slipped,
  );
  const considered = running.length > 0 ? running : state.m;
  let latestEnd = -Infinity;
  for (const member of considered) {
    const end = member.s === MemberState.paused && member.q !== undefined ? now + (member.e - member.q) : member.e;
    latestEnd = Math.max(latestEnd, end);
  }
  if (latestEnd === -Infinity) latestEnd = now;
  return Math.ceil(latestEnd + STALE_AFTER_END_SECONDS);
}

export type LiveActivityEvent = "update" | "end" | "start";

export interface LiveActivityAlert {
  title: string;
  body: string;
  sound?: string;
}

export interface LiveActivityPayloadOptions {
  event: LiveActivityEvent;
  state: ContentState;
  /** When this state was produced, Unix seconds. ActivityKit ignores a push older than the last one it applied. */
  timestamp: number;
  staleDate?: number;
  /** `end` only. Defaults to `timestamp` + 30 minutes. */
  dismissalDate?: number;
  relevanceScore?: number;
  /** Required for `start` (push-to-start must be visible); allowed on `update`. Never on routine squad events (SPEC.md §4.4). */
  alert?: LiveActivityAlert;
  /** `start` only. Defaults to `LockinAttributes`. */
  attributesType?: string;
  /** `start` only, and required there. */
  attributes?: Attributes;
  /**
   * `start` only. Defaults to true: every supported iOS (18.0+) needs `input-push-token: 1` to hand
   * the new activity's update token to the app (CLAUDE.md). Pass false only when starting with
   * `input-push-channel` instead.
   */
  inputPushToken?: boolean;
}

export interface LiveActivityPayload {
  aps: {
    timestamp: number;
    event: LiveActivityEvent;
    "content-state": ContentState;
    "stale-date"?: number;
    "dismissal-date"?: number;
    "relevance-score"?: number;
    alert?: LiveActivityAlert;
    "attributes-type"?: string;
    attributes?: Attributes;
    "input-push-token"?: 1;
  };
}

function parseAlert(value: unknown): LiveActivityAlert {
  const record = object(value, "alert", ["title", "body"], ["sound"]);
  if (typeof record.title !== "string" || record.title.length === 0) fail("alert.title", "must be a non-empty string");
  if (typeof record.body !== "string" || record.body.length === 0) fail("alert.body", "must be a non-empty string");
  const alert: LiveActivityAlert = { title: record.title, body: record.body };
  if (record.sound !== undefined) {
    if (typeof record.sound !== "string") fail("alert.sound", "must be a string");
    alert.sound = record.sound;
  }
  return alert;
}

/**
 * The APNs body for a Live Activity push (the `aps` dictionary). Validates the state again on the
 * way out, because this is the last stop before a phone silently drops a bad update.
 *
 * Push-to-start (`start`) follows Apple's rules (SPEC.md §3, §4.5): it must carry an alert, the
 * attributes type and the attributes, and the attributes count against the payload budget.
 *
 * The whole body, alert and all, must also fit APNs' `APNS_BODY_LIMIT_BYTES`.
 */
export function buildLiveActivityPayload(options: LiveActivityPayloadOptions): LiveActivityPayload {
  const { event } = options;
  if (event !== "update" && event !== "end" && event !== "start") fail("event", "must be update, end or start");
  const state = parseContentState(options.state);
  const timestamp = Math.floor(time(options.timestamp, "timestamp"));

  const aps: LiveActivityPayload["aps"] = { timestamp, event, "content-state": state };
  if (options.staleDate !== undefined) aps["stale-date"] = Math.ceil(time(options.staleDate, "staleDate"));

  if (event === "end") {
    const dismissal = options.dismissalDate ?? timestamp + END_DISMISSAL_SECONDS;
    aps["dismissal-date"] = Math.ceil(time(dismissal, "dismissalDate"));
  } else if (options.dismissalDate !== undefined) {
    fail("dismissalDate", "is only for end events");
  }

  if (options.relevanceScore !== undefined) {
    if (!Number.isFinite(options.relevanceScore)) fail("relevanceScore", "must be a finite number");
    aps["relevance-score"] = options.relevanceScore;
  }

  if (event === "start") {
    if (options.alert === undefined) fail("alert", "is required to start a Live Activity by push");
    if (options.attributes === undefined) fail("attributes", "are required to start a Live Activity by push");
    aps.alert = parseAlert(options.alert);
    aps["attributes-type"] = options.attributesType ?? ATTRIBUTES_TYPE;
    if (aps["attributes-type"].length === 0) fail("attributesType", "must not be empty");
    aps.attributes = parseAttributes(options.attributes);
    if (options.inputPushToken !== false) aps["input-push-token"] = 1;
    assertPayloadBudget(aps.attributes, state);
  } else {
    if (options.alert !== undefined) aps.alert = parseAlert(options.alert);
    if (options.attributesType !== undefined || options.attributes !== undefined || options.inputPushToken !== undefined) {
      fail(event, "pushes can't carry attributesType, attributes or inputPushToken: those are for start");
    }
  }

  const payload = { aps };
  const bytes = utf8.encode(JSON.stringify(payload)).length;
  if (bytes > APNS_BODY_LIMIT_BYTES) {
    throw new LiveActivityError(`The APNs body is ${bytes} bytes; APNs takes at most ${APNS_BODY_LIMIT_BYTES}`);
  }
  return payload;
}
